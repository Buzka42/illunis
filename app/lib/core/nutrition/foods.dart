FoodEstimate? lookupFood(String raw) {
  final n = foldLatin(raw).replaceAll(RegExp(r'[^a-z0-9]+'), ' ').trim();
  if (n.isEmpty) return null;
  FoodEstimate? best;
  var bestLen = 0;
  for (final f in kFoods) {
    for (final a in [...f.aliases, f.label.toLowerCase()]) {
      final token = foldLatin(a).trim();
      if (token.isEmpty) continue;
      if (RegExp('\\b${RegExp.escape(token)}\\b').hasMatch(n) &&
          token.length > bestLen) {
        best = f;
        bestLen = token.length;
      }
    }
  }
  return best;
}
