#!/usr/bin/env python3
"""Build app/lib/core/sky/star_catalog.dart from HYG (Hipparcos+Yale+Gliese).

Source: HYG v3 (CC-BY-SA 2.5), mag V <= 6.0, Sol excluded.
Re-run after placing a HYG csv/gz at tool/stars/src.bin (or pass a path).
"""

from __future__ import annotations

import base64
import csv
import gzip
import math
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "app" / "lib" / "core" / "sky" / "star_catalog.dart"
KEEP_NAMES = {
    "Sirius",
    "Canopus",
    "Arcturus",
    "Vega",
    "Capella",
    "Rigel",
    "Procyon",
    "Betelgeuse",
    "Altair",
    "Aldebaran",
    "Antares",
    "Spica",
    "Pollux",
    "Fomalhaut",
    "Deneb",
    "Regulus",
    "Polaris",
    "Alnitak",
    "Alnilam",
    "Mintaka",
}


def open_text(path: Path):
    raw = path.read_bytes()[:2]
    if raw == b"\x1f\x8b":
        return gzip.open(path, "rt", encoding="utf-8", errors="replace")
    return path.open("rt", encoding="utf-8", errors="replace")


def load_stars(path: Path) -> list[dict]:
    stars = []
    with open_text(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            if row.get("id") == "0":
                continue
            mag_s = row.get("mag") or ""
            if mag_s == "":
                continue
            mag = float(mag_s)
            if mag > 6.0:
                continue
            ra = row.get("rarad") or ""
            dec = row.get("decrad") or ""
            if ra and dec:
                ra_rad = float(ra)
                dec_rad = float(dec)
            else:
                ra_rad = float(row["ra"]) * math.pi / 180.0
                dec_rad = float(row["dec"]) * math.pi / 180.0
            ci = row.get("ci") or ""
            bv = float(ci) if ci else 0.0
            if not math.isfinite(bv):
                bv = 0.0
            stars.append(
                {
                    "ra": ra_rad,
                    "dec": dec_rad,
                    "mag": mag,
                    "bv": bv,
                    "proper": (row.get("proper") or "").strip(),
                }
            )
    stars.sort(key=lambda s: s["mag"])
    return stars


def main() -> int:
    src = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tool" / "stars" / "src.bin"
    if not src.exists():
        print(f"missing catalog at {src}", file=sys.stderr)
        return 1
    stars = load_stars(src)
    buf = bytearray()
    names: dict[str, int] = {}
    for i, s in enumerate(stars):
        buf += struct.pack("<ffff", s["ra"], s["dec"], s["mag"], s["bv"])
        if s["proper"] in KEEP_NAMES and s["proper"] not in names:
            names[s["proper"]] = i
    b64 = base64.b64encode(bytes(buf)).decode("ascii")
    wrapped = "\n".join(b64[i : i + 76] for i in range(0, len(b64), 76))
    name_entries = ",\n".join(
        f"  '{k}': {names[k]}" for k in sorted(names, key=lambda n: names[n])
    )
    OUT.write_text(
        f"""// GENERATED by tool/stars/generate.py — do not edit.
// HYG v3 (Hipparcos + Yale Bright Star + Gliese), CC-BY-SA 2.5,
// David Nash / astronexus. Visual magnitude V <= 6.0, Sol omitted.
// Packed little-endian float32: raRad, decRad, vMag, bMinusV.

import 'dart:convert';
import 'dart:typed_data';

const kStarCount = {len(stars)};

const _kStarB64 = '''
{wrapped}
''';

Float32List? _starPack;

/// Packed catalog. Length is [kStarCount] * 4.
Float32List get kStarPack {{
  if (_starPack != null) return _starPack!;
  final bytes = Uint8List.fromList(
    base64Decode(_kStarB64.replaceAll('\\n', '')),
  );
  return _starPack = Float32List.view(bytes.buffer);
}}

/// Proper-name lookup into [kStarPack] (brightest-first).
const kStarNameIndex = <String, int>{{
{name_entries}
}};
""",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(stars)} stars, {len(names)} names)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
